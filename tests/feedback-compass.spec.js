test('feedback is sent to Formspree, with the calculator and reply-to email', async ({ page }) => {
  const errors = await openSite(page)
  let sent = null
  await page.route('https://formspree.io/**', async (route) => { // never reaches the real form
    sent = route.request().postDataJSON()
    await route.fulfill({ status: 200, contentType: 'application/json', body: '{"ok":true}' })
  })
  await openCalc(page, 'ach')
  await page.locator('#calc-fb').click()
  await page.locator('#fb-msg').fill('Great tool')
  await page.locator('#fb-email').fill('not-an-email')
  await page.locator('#fb-send').click()
  await expect(page.locator('#fb-email-err')).toBeVisible()
  expect(sent).toBeNull()

  await page.locator('#fb-email').fill('engr@example.com')
  await page.locator('#fb-send').click()
  await expect(page.locator('#fb-done')).toHaveText('✓ Sent — thank you!', { timeout: 15000 })
  expect(sent).toMatchObject({ type: 'Suggestion', message: 'Great tool', email: 'engr@example.com', calculator: 'Air Changes Calculator', _gotcha: '' })
  expect(sent._subject).toBe('MechToolBox feedback — Suggestion — Air Changes Calculator')
  expect(sent.details).toContain('--- Calculator ---')
  await expect(page.locator('#fb-msg')).toHaveValue('') // the message clears, the email stays
  await expect(page.locator('#fb-email')).toHaveValue('engr@example.com')
  expect(errors).toEqual([])
})

test('a failed send keeps the message and says why', async ({ page }) => {
  await openSite(page)
  await page.route('https://formspree.io/**', (route) => route.fulfill({ status: 422, contentType: 'application/json', body: '{"errors":[{"message":"Form not found"}]}' }))
  await page.locator('#fb-fab').click()
  await page.locator('#fb-msg').fill('Hello')
  await page.locator('#fb-send').click()
  await expect(page.locator('#fb-done')).toContainText('Couldn’t send (Form not found)', { timeout: 15000 })
  await expect(page.locator('#fb-msg')).toHaveValue('Hello')
  await expect(page.locator('#fb-send')).toBeEnabled()
})

test('compass turns with the device heading and shows the sun', async ({ page }) => {
  const errors = await openSite(page)
  await page.locator('#cp-btn').click()
  await expect(page.locator('#cp-panel')).toBeVisible()
  await expect(page.locator('#cp-sun')).toContainText('°')
  // Android-style absolute orientation: alpha 90 → heading 270° W
  await page.evaluate(() => window.dispatchEvent(new DeviceOrientationEvent('deviceorientationabsolute', { alpha: 90, absolute: true })))
  await expect(page.locator('#cp-head')).toHaveText('270° W')
  await expect(page.locator('#compass')).toHaveClass(/live/)
  await page.keyboard.press('Escape')
  await expect(page.locator('#cp-panel')).toBeHidden()
  expect(errors).toEqual([])
})

test('floating converter converts as you type and lists constants', async ({ page }) => {
  const errors = await openSite(page)
  await page.locator('#cv-btn').click()
  await expect(page.locator('#cv-panel')).toBeVisible()
  await page.locator('[data-cvcat="Power"]').click()
  await page.locator('#cv-from').selectOption('TR')
  await page.locator('#cv-to').selectOption('kW')
  await page.locator('#cv-val').fill('1')
  await expect(page.locator('#cv-out')).toHaveText('3.51685')
  await page.locator('#cv-swap').click()                      // kW → TR
  await expect(page.locator('#cv-out')).toHaveText('0.284345')
  await expect(page.locator('#cv-all')).toContainText('BTU/h')
  await page.locator('[data-cvtab="const"]').click()
  await page.locator('#cs-q').fill('gravity')
  await expect(page.locator('#cs-list .cs-ul li')).toHaveCount(1)
  await expect(page.locator('#cs-list')).toContainText('9.80665 m/s²')
  await page.locator('#cs-list .cs-v').first().click()
  await expect(page.locator('#cv-msg')).toContainText('Copied 9.80665 m/s²')
  await page.keyboard.press('Escape')
  await expect(page.locator('#cv-panel')).toBeHidden()
  expect(errors).toEqual([])
})

test('altimeter falls back to ground elevation and feeds the psychrometric chart', async ({ page, context }) => {
  const errors = await openSite(page)
  await context.grantPermissions(['geolocation'])
  await context.setGeolocation({ latitude: 16.4023, longitude: 120.596 })          // Baguio — no GPS altitude in the browser
  await page.route('**/api.open-meteo.com/**', (r) => r.fulfill({ contentType: 'application/json', body: '{"elevation":[1500]}' }))
  await page.locator('#cp-btn').click()
  await page.locator('#cp-alt-btn').click()
  await expect(page.locator('#cp-alt')).toHaveText('1,500 m')
  await expect(page.locator('#cp-alt-src')).toContainText('84.6 kPa')
  await page.locator('#cp-alt-psy').click()
  await expect(page.locator('#psy-alt')).toHaveValue('1500')
  expect(errors).toEqual([])
})

test('the converter and compass hide into the side and come back, remembered after reload', async ({ page }) => {
  const errors = await openSite(page)
  await expect(page.locator('#cv-btn')).toBeVisible()
  await page.locator('#dock-tab').click()
  await expect(page.locator('body')).toHaveClass(/dock-hidden/)
  await expect(page.locator('#dock-tab')).toHaveAttribute('aria-expanded', 'false')
  await page.reload()
  await expect(page.locator('body')).toHaveClass(/dock-hidden/)
  await page.locator('#dock-tab').click()
  await expect(page.locator('body')).not.toHaveClass(/dock-hidden/)
  await page.locator('#cv-btn').click()
  await expect(page.locator('#cv-panel')).toBeVisible()
  expect(errors).toEqual([])
})
